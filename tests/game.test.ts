import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { pool } from '../src/db.js';
import * as game from '../src/game.js';
import * as transfer from '../src/transfer.js';
import * as combat from '../src/combat.js';
import * as branches from '../src/branches.js';
import { createKey, authenticate } from '../src/auth.js';

test('two to eight players, group isolation, idempotent rolls and three autosaves',async()=>{
  const db=new PGlite();
  const schema=await readFile(new URL('../sql/001_init.sql',import.meta.url),'utf8');
  await db.exec(schema);
  await db.exec(schema);
  const oldQuery=pool.query.bind(pool),oldConnect=pool.connect.bind(pool);
  (pool as any).query=(sql:string,params?:unknown[])=>db.query(sql,params);
  (pool as any).connect=async()=>({query:(sql:string,params?:unknown[])=>db.query(sql,params),release:()=>{}});
  const actor=(userId:string,requestId:string,groupId='group-a')=>({groupId,userId,messageId:requestId,requestId,keyId:'key',permissions:['read','world','game','dm','save','owner']});
  try{
    const created=await createKey('测试 QQ AI',['group-a'],['read','game']);
    const stored=await db.query('SELECT key_hash FROM api_keys WHERE id=$1',[created.id]);
    assert.notEqual(stored.rows[0].key_hash,created.key);
    const request=(groupId:string)=>({headers:{authorization:`Bearer ${created.key}`,'x-qq-group-id':groupId,'x-qq-user-id':'a','x-qq-message-id':'m','x-request-id':'r','x-qq-message-time':'2026-10-27T00:00:00Z'},ip:'127.0.0.1'}) as any;
    assert.equal((await authenticate(request('group-a'))).groupId,'group-a');
    await assert.rejects(authenticate(request('group-b')),/未授权/);
    await db.query('UPDATE api_keys SET enabled=false WHERE id=$1',[created.id]);
    await assert.rejects(authenticate(request('group-a')),/无效/);
    const w=await game.createWorld(actor('a','create'),'测试世界',{});
    const id=w.worldId;
    await game.joinWorld(actor('b','join-b'),id);
    await assert.rejects(game.createCharacter(actor('a','invalid-hp'),id,{name:'过高生命',species:'人类',class:'战士',hpMax:500,ac:16}),/初始生命值超出/);
    await game.createCharacter(actor('a','char-a'),id,{name:'战士',species:'人类',class:'战士',hpMax:12,ac:16});
    await game.createCharacter(actor('b','char-b'),id,{name:'法师',species:'精灵',class:'法师',hpMax:8,ac:12,spells:['magic_missile','fire_bolt']});
    await game.ready(actor('a','ready-a'),id,true);
    await game.ready(actor('b','ready-b'),id,true);
    assert.equal((await game.startCampaign(actor('a','start'),id)).players,2);
    assert.equal((await game.players(actor('a','list'),id)).length,2);
    const aCharacter=(await game.characters(actor('a','own-character'),id)).find((x:any)=>x.user_id==='a');
    await assert.rejects(game.levelUpCharacter(actor('a','early-level'),id,aCharacter.id),/经验值不足/);
    await game.awardExperience(actor('a','award-xp'),id,aCharacter.id,300);
    assert.equal((await game.levelUpCharacter(actor('a','level-up'),id,aCharacter.id)).sheet.level,2);
    const battle=await combat.startCombat(actor('a','battle'),id,[{name:'哥布林',hp:12,ac:12,initiativeBonus:0}]);
    const current=battle.order[0];
    const ownerOfCurrent=current.kind==='enemy'?'a':(await game.characters(actor('a','combat-characters'),id)).find((x:any)=>x.id===current.id).user_id;
    const target=current.kind==='enemy'?battle.order.find((x:any)=>x.kind==='player'&&x.name==='战士'):battle.order.find((x:any)=>x.kind==='enemy');
    const attack=await combat.combatAction(actor(ownerOfCurrent,'attack'),id,'attack',target.id);
    const again=await combat.combatAction(actor(ownerOfCurrent,'attack'),id,'attack',target.id);
    assert.deepEqual(again,attack);
    await assert.rejects(combat.combatAction(actor(ownerOfCurrent,'second-attack'),id,'attack',target.id),/已使用动作/);
    await combat.endTurn(actor(ownerOfCurrent,'end-turn'),id);
    await combat.endCombat(actor('a','end-battle'),id);
    const bBefore=(await game.characters(actor('a','before-leave'),id)).find((x:any)=>x.user_id==='b');
    await game.leaveWorld(actor('b','leave-b'),id);
    await assert.rejects(game.submitAction(actor('b','offline-action'),id,'离线行动'),/尚未加入/);
    await game.joinWorld(actor('b','rejoin-b'),id);
    assert.equal((await game.characters(actor('a','after-rejoin'),id)).find((x:any)=>x.user_id==='b').id,bBefore.id);
    const action=await game.submitAction(actor('a','inspect-door'),id,'检查门上的符文');
    const check=await game.adjudicateAction(actor('a','check-door'),id,action.actionId,'intelligence',12);
    assert.equal((await game.adjudicateAction(actor('a','check-door'),id,action.actionId,'intelligence',12)).rollId,check.rollId);
    await game.resolveAction(actor('a','resolve-door'),id,action.actionId,check.success?'发现机关':'未发现机关',{scene:'古老石门'});
    assert.equal((await game.getWorld(actor('a','current-scene'),id)).state.scene,'古老石门');
    await assert.rejects(game.getWorld(actor('x','foreign','group-b'),id),/不属于/);
    await assert.rejects(game.storyContext({...actor('a','private-denied'),permissions:['read']},id,true),/dm/);
    const r1=await game.rollDice(actor('a','roll'),id,'1d20+2');
    const r2=await game.rollDice(actor('a','roll'),id,'1d20+2');
    assert.deepEqual(r2,r1);
    for(let n=1;n<=4;n++)await game.createSave(actor('a',`save-${n}`),id,'auto',`自动 ${n}`);
    const saves=await game.listSaves(actor('a','saves'),id);
    assert.deepEqual(saves.filter((s:any)=>s.kind==='auto').map((s:any)=>Number(s.version)),[4,3,2]);
    (pool as any).connect=async()=>({query:(sql:string,params?:unknown[])=>sql.includes('UPDATE worlds SET save_sequence')?Promise.reject(new Error('storage failure')):db.query(sql,params),release:()=>{}});
    await assert.rejects(game.createSave(actor('a','failed-save'),id,'auto','失败存档'),/storage failure/);
    (pool as any).connect=async()=>({query:(sql:string,params?:unknown[])=>db.query(sql,params),release:()=>{}});
    assert.deepEqual((await game.listSaves(actor('a','after-failure'),id)).filter((s:any)=>s.kind==='auto').map((s:any)=>Number(s.version)),[4,3,2]);
    let serializationConflict=true;
    (pool as any).connect=async()=>({query:(sql:string,params?:unknown[])=>{
      if(sql.includes('UPDATE worlds SET save_sequence')&&serializationConflict){serializationConflict=false;return Promise.reject(Object.assign(new Error('serialization'),{code:'40001'}));}
      return db.query(sql,params);
    },release:()=>{}});
    assert.equal((await game.createSave(actor('a','retry-save'),id,'auto','重试存档')).version,5);
    (pool as any).connect=async()=>({query:(sql:string,params?:unknown[])=>db.query(sql,params),release:()=>{}});
    for(let n=3;n<=8;n++){
      assert.deepEqual(await game.joinWorld(actor(`player-${n}`,`join-${n}`),id),{joined:true,count:n});
      await game.createCharacter(actor(`player-${n}`,`char-${n}`),id,{name:`角色 ${n}`,species:'人类',class:n===3?'牧师':'战士',hpMax:10,ac:12,spells:n===3?['cure_wounds']:[]});
    }
    assert.equal((await game.players(actor('a','list-eight'),id)).length,8);
    assert.equal((await game.characters(actor('a','characters'),id)).length,8);
    await assert.rejects(game.joinWorld(actor('ninth','join-nine'),id),/最多 8/);
    const b=(await game.characters(actor('a','b-char'),id)).find((x:any)=>x.user_id==='b');
    await assert.rejects(game.updateCharacter(actor('a','modify-b'),id,b.id,{goal:'changed'}),/只能修改自己的角色/);
    const manual=await game.createSave(actor('a','manual'),id,'manual','决战前');
    for(let n=2;n<=5;n++)await game.createSave(actor('a',`manual-${n}`),id,'manual',`手动 ${n}`);
    await assert.rejects(game.createSave(actor('a','manual-six'),id,'manual','第六个'),/已达 5 个/);
    await db.query('UPDATE server_settings SET recycle_save_limit=1 WHERE id=true');
    const manualSaves=await game.listSaves(actor('a','manual-list'),id);
    const fourth=manualSaves.find((s:any)=>s.name==='手动 4');
    const fifth=manualSaves.find((s:any)=>s.name==='手动 5');
    const firstDelete=await game.requestConfirmation(actor('a','delete-fifth-request'),id,'save_delete',fifth.id);
    await game.deleteSave(actor('a','delete-fifth'),id,fifth.id,firstDelete.confirmationToken);
    const secondDelete=await game.requestConfirmation(actor('a','delete-fourth-request'),id,'save_delete',fourth.id);
    await assert.rejects(game.deleteSave(actor('a','delete-fourth-full'),id,fourth.id,secondDelete.confirmationToken),/回收站已满/);
    assert.equal((await game.previewCleanup(actor('a','preview-cleanup'),id)).deletedSaves.length,1);
    const purge=await game.requestConfirmation(actor('a','purge-request'),id,'save_purge',fifth.id);
    await game.cleanupSave(actor('a','purge'),id,fifth.id,purge.confirmationToken);
    await game.deleteSave(actor('a','delete-fourth'),id,fourth.id,secondDelete.confirmationToken);
    await game.recoverSave(actor('a','recover-fourth'),id,fourth.id);
    assert.equal((await game.previewCleanup(actor('a','preview-empty'),id)).deletedSaves.length,0);
    await game.advanceScene(actor('a','advance'),id,{scene:'战场',location:'王城'});
    assert.equal((await game.getWorld(actor('a','read-new'),id)).state.location,'王城');
    const restore=await game.requestConfirmation(actor('a','restore-request'),id,'save_restore',manual.saveId);
    await game.restoreSave(actor('a','restore'),id,manual.saveId,restore.confirmationToken);
    assert.equal((await game.getWorld(actor('a','read-restored'),id)).state.location,'');
    await game.advanceScene(actor('a','branch-scene'),id,{location:'地下城'});
    const branch=await branches.branchFromSave(actor('a','create-branch'),id,manual.saveId,'另一条路');
    assert.equal((await game.getWorld(actor('a','branch-current'),id)).state.location,'');
    const main=(await branches.listBranches(actor('a','branches'),id)).find((x:any)=>!x.active);
    await branches.switchBranch(actor('a','switch-main'),id,main.id);
    assert.equal((await game.getWorld(actor('a','main-current'),id)).state.location,'地下城');
    await branches.switchBranch(actor('a','switch-alt'),id,branch.branchId);
    const branchDelete=await game.requestConfirmation(actor('a','branch-delete-request'),id,'branch_delete',main.id);
    await branches.deleteBranch(actor('a','branch-delete'),id,main.id,branchDelete.confirmationToken);
    assert.equal((await branches.listBranches(actor('a','remaining-branches'),id)).length,1);
    const exported=await transfer.exportWorld(actor('a','export'),id);
    await assert.rejects(transfer.readExportChunk(actor('a','foreign-export','group-b'),exported.exportId,0),/不存在/);
    const incoming=await transfer.beginImport(actor('a','begin-import'),exported.chunks);
    for(let i=0;i<exported.chunks;i++){
      const chunk=await transfer.readExportChunk(actor('a',`read-${i}`),exported.exportId,i);
      await transfer.uploadImportChunk(actor('a',`upload-${i}`),incoming.importId,i,chunk.base64);
    }
    const imported=await transfer.importWorld(actor('a','final-import'),incoming.importId);
    assert.equal((await game.characters(actor('a','import-chars'),imported.worldId)).length,8);
    const deletion=await game.requestConfirmation(actor('a','delete-request'),id,'world_delete');
    await game.deleteWorld(actor('a','delete'),id,deletion.confirmationToken);
    await assert.rejects(game.getWorld(actor('a','deleted'),id),/不存在/);
    await game.recoverWorld(actor('a','recover'),id);
    assert.equal((await game.getWorld(actor('a','recovered'),id)).name,'测试世界');
    const deathBattle=await combat.startCombat(actor('a','death-battle'),id,[]);
    deathBattle.index=deathBattle.order.findIndex((x:any)=>x.id===aCharacter.id);
    const fallen=deathBattle.order[deathBattle.index];fallen.hp=0;
    await db.query('UPDATE combats SET state=$2 WHERE world_id=$1',[id,JSON.stringify(deathBattle)]);
    const fallenRow=await db.query('SELECT user_id,sheet FROM characters WHERE id=$1',[fallen.id]);
    await db.query('UPDATE characters SET sheet=$2 WHERE id=$1',[fallen.id,JSON.stringify({...fallenRow.rows[0].sheet,hp:0})]);
    const fallenActor=actor(fallenRow.rows[0].user_id,'death-roll');
    await assert.rejects(combat.endTurn(actor(fallenRow.rows[0].user_id,'skip-death'),id),/先进行死亡豁免/);
    const deathRoll=await combat.deathSave(fallenActor,id);
    assert.deepEqual(await combat.deathSave(fallenActor,id),deathRoll);
    assert.deepEqual((await db.query('SELECT raw FROM dice_rolls WHERE id=$1',[deathRoll.rollId])).rows[0].raw,[deathRoll.roll]);
    await combat.endTurn(actor(fallenRow.rows[0].user_id,'after-death-roll'),id);
    const itemBattle=(await combat.combatState(actor('a','item-battle-state'),id)).state;
    const itemUser=itemBattle.order[itemBattle.index];itemUser.hp=Math.max(1,itemUser.hpMax-5);
    const itemRow=await db.query('SELECT user_id,sheet FROM characters WHERE id=$1',[itemUser.id]);
    await db.query('UPDATE combats SET state=$2 WHERE world_id=$1',[id,JSON.stringify(itemBattle)]);
    await db.query('UPDATE characters SET sheet=$2 WHERE id=$1',[itemUser.id,JSON.stringify({...itemRow.rows[0].sheet,hp:itemUser.hp})]);
    await game.grantItem(actor('a','grant-potion'),id,itemUser.id,'healing_potion',1);
    const potionActor=actor(itemRow.rows[0].user_id,'drink-potion');
    const potion=await combat.useItem(potionActor,id,'healing_potion');
    assert.deepEqual(await combat.useItem(potionActor,id,'healing_potion'),potion);
    assert.deepEqual((await db.query('SELECT raw FROM dice_rolls WHERE id=$1',[potion.rollId])).rows[0].raw,potion.rolls);
    assert.equal((await db.query('SELECT sheet FROM characters WHERE id=$1',[itemUser.id])).rows[0].sheet.equipment.length,0);
    await combat.endCombat(actor('a','end-death-battle'),id);
    await game.finishLongRest(actor('a','rest-before-spells'),id);
    assert.equal((await db.query('SELECT sheet FROM characters WHERE id=$1',[b.id])).rows[0].sheet.spellSlots['1'],2);
    const spellBattle=await combat.startCombat(actor('a','spell-battle'),id,[{name:'训练假人',hp:100,ac:10,initiativeBonus:0}]);
    const spellEnemy=spellBattle.order.find((x:any)=>x.kind==='enemy');
    spellBattle.index=spellBattle.order.findIndex((x:any)=>x.id===b.id);
    spellBattle.usedAction=false;
    await db.query('UPDATE combats SET state=$2 WHERE world_id=$1',[id,JSON.stringify(spellBattle)]);
    const missile=await combat.castSpell(actor('b','magic-missile'),id,'magic_missile',spellEnemy.id,1);
    assert.deepEqual(await combat.castSpell(actor('b','magic-missile'),id,'magic_missile',spellEnemy.id,1),missile);
    assert.equal(missile.rolls.length,3);
    assert.equal((await db.query('SELECT sheet FROM characters WHERE id=$1',[b.id])).rows[0].sheet.spellSlots['1'],1);
    await assert.rejects(combat.castSpell(actor('b','same-turn-fire'),id,'fire_bolt',spellEnemy.id,0),/已使用动作/);
    const fireState=(await combat.combatState(actor('a','fire-state'),id)).state;
    fireState.usedAction=false;
    await db.query('UPDATE combats SET state=$2 WHERE world_id=$1',[id,JSON.stringify(fireState)]);
    const fire=await combat.castSpell(actor('b','fire-bolt'),id,'fire_bolt',spellEnemy.id,0);
    assert.ok(fire.attackRollId);
    assert.equal((await db.query('SELECT sheet FROM characters WHERE id=$1',[b.id])).rows[0].sheet.spellSlots['1'],1);
    const cleric=(await game.characters(actor('a','cleric-character'),id)).find((x:any)=>x.user_id==='player-3');
    const cureState=(await combat.combatState(actor('a','cure-state'),id)).state;
    cureState.index=cureState.order.findIndex((x:any)=>x.id===cleric.id);
    cureState.order[cureState.index].hp=5;cureState.usedAction=false;
    await db.query('UPDATE combats SET state=$2 WHERE world_id=$1',[id,JSON.stringify(cureState)]);
    await db.query('UPDATE characters SET sheet=$2 WHERE id=$1',[cleric.id,JSON.stringify({...cleric.sheet,hp:5})]);
    const cure=await combat.castSpell(actor('player-3','cure-wounds'),id,'cure_wounds',cleric.id,1);
    assert.ok(cure.targetHp>5);
    assert.equal((await db.query('SELECT sheet FROM characters WHERE id=$1',[cleric.id])).rows[0].sheet.spellSlots['1'],1);
    await combat.endCombat(actor('a','end-spell-battle'),id);
    await game.finishLongRest(actor('a','rest-after-spells'),id);
    assert.equal((await db.query('SELECT sheet FROM characters WHERE id=$1',[b.id])).rows[0].sheet.spellSlots['1'],2);
    const discarded:string[]=[];
    for(let n=1;n<=3;n++){
      const other=await game.createWorld(actor('a',`discard-world-${n}`),`待清理 ${n}`,{});
      discarded.push(other.worldId);
      const token=await game.requestConfirmation(actor('a',`discard-request-${n}`),other.worldId,'world_delete');
      await game.deleteWorld(actor('a',`discard-${n}`),other.worldId,token.confirmationToken);
    }
    const fourthWorld=await game.createWorld(actor('a','fourth-world'),'第四个待清理世界',{});
    const fourthToken=await game.requestConfirmation(actor('a','fourth-delete-request'),fourthWorld.worldId,'world_delete');
    await assert.rejects(game.deleteWorld(actor('a','fourth-delete-full'),fourthWorld.worldId,fourthToken.confirmationToken),/回收站已满/);
    const purgeWorldToken=await game.requestConfirmation(actor('a','world-purge-request'),discarded[0],'world_purge');
    await game.purgeWorld(actor('a','world-purge'),discarded[0],purgeWorldToken.confirmationToken);
    await game.deleteWorld(actor('a','fourth-delete'),fourthWorld.worldId,fourthToken.confirmationToken);
  }finally{
    (pool as any).query=oldQuery;(pool as any).connect=oldConnect;await db.close();
  }
});
